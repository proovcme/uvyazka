def _looks_like_numeric_grid(sample: str) -> bool:
    text = _norm_text(sample)
    simple = re.sub(r"[|\s]+", " ", text).strip()
    if simple in {"1 2", "1 2 3", "l, м"}:
        return True
    tokens = simple.split()
    if len(tokens) < 5:
        return False
