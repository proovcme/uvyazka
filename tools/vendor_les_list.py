"""Reproduce the selected pure LIST functions from the pinned, local source checkout.

Never imports or runs the source repository. No network, runtime, database or UI copied.
"""
import argparse
import ast
import hashlib
import json
from pathlib import Path
import subprocess

COMMIT = "f6bedb34eff75c2d47e772810220ff738183f804"
MODULES = {"project_pdf_table_service": "tables", "pd_rd_manifest_service": "structure",
           "drawing_manifest_service": "text_repair"}
ROOTS = {
    "project_pdf_table_service": {"classify_project_table_semantic", "classify_project_table",
        "normalize_hvs_table", "normalize_water_balance_table", "normalize_room_explication_table", "_table_context"},
    "pd_rd_manifest_service": {"repair_pd_rd_text", "_parse_volume_contents_lines",
        "_parse_project_composition_lines", "_looks_like_project_composition_lines", "_parse_pz_toc_lines", "_clean_line"},
    "drawing_manifest_service": set(),
}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    args = parser.parse_args()
    actual = subprocess.check_output(["git", "-C", str(args.source), "rev-parse", "HEAD"], text=True).strip()
    if actual != COMMIT:
        raise ValueError("Use reviewed LIST commit " + COMMIT)
    reviewed_files = ["proxy/services/"+mod+".py" for mod in MODULES] + ["LICENSE"]
    subprocess.run(["git", "-C", str(args.source), "diff", "--exit-code", COMMIT, "--", *reviewed_files],
                   check=True, capture_output=True)
    package = Path(__file__).resolve().parents[1]/"src/uvyazka/_vendor/les_list"
    package.mkdir(parents=True, exist_ok=True)
    (package.parent/"__init__.py").write_text('"""Attributed, selectively vendored code."""\n', encoding="utf-8")
    (package/"__init__.py").write_text('"""Pure LIST heuristics. See LICENSE.txt and provenance.json."""\n', encoding="utf-8")
    sources, trees, definitions, imports = {}, {}, {}, {}
    selected = {k: set(v) for k, v in ROOTS.items()}
    for mod in MODULES:
        path = args.source/"proxy/services"/(mod+".py")
        sources[mod] = path.read_text(encoding="utf-8")
        trees[mod] = ast.parse(sources[mod])
        definitions[mod], imports[mod] = {}, {}
        for node in trees[mod].body:
            if isinstance(node, (ast.FunctionDef, ast.ClassDef)):
                definitions[mod][node.name] = node
            elif isinstance(node, (ast.Assign, ast.AnnAssign)):
                for target in node.targets if isinstance(node, ast.Assign) else [node.target]:
                    if isinstance(target, ast.Name): definitions[mod][target.id] = node
            elif isinstance(node, ast.ImportFrom) and (node.module or "").startswith("proxy.services."):
                for name in node.names: imports[mod][name.asname or name.name] = (node.module.rsplit(".", 1)[-1], name.name)
    changed = True
    while changed:
        before = sum(map(len, selected.values()))
        for mod in MODULES:
            for name in list(selected[mod]):
                node = definitions[mod].get(name)
                if node is None:
                    dependency, original = imports[mod][name]
                    selected[dependency].add(original)
                    continue
                for use in ast.walk(node):
                    if isinstance(use, ast.Name) and (use.id in definitions[mod] or use.id in imports[mod]):
                        selected[mod].add(use.id)
        changed = sum(map(len, selected.values())) != before
    records = []
    for mod, target in MODULES.items():
        parts = ['"""Selected LIST heuristics; Copyright (c) 2026 OVC, MIT. See LICENSE.txt.\n'
                 'Generated by tools/vendor_les_list.py; local changes recorded in provenance.json.\n"""',
                 "from __future__ import annotations", "import re", "import hashlib", "import math", "from typing import Any"]
        for name in sorted(selected[mod] & imports[mod].keys()):
            dependency, original = imports[mod][name]
            parts.append(f"from .{MODULES[dependency]} import {original}" + (f" as {name}" if name != original else ""))
        for node in trees[mod].body:
            if any(node is definitions[mod].get(name) for name in selected[mod]):
                parts.append(ast.get_source_segment(sources[mod], node))
        output = "\n\n".join(parts) + "\n"
        changes = []
        if target == "tables":
            # Source row addresses must survive blank lines in a detected table.
            old = 'rows = [[_clean_cell(cell) for cell in row] for row in matrix if any(_clean_cell(cell) for cell in row)]'
            start = output.index('def _prepare_table(')
            output = output[:start] + output[start:].replace(old,
                'rows = [[_clean_cell(cell) for cell in row] for row in matrix]', 1)
            old_num = ast.get_source_segment(sources[mod], definitions[mod]['_num'])
            output = output.replace(old_num, '''def _num(value: Any) -> float | None:
    """Only an unambiguous scalar; ranges, expressions and attached units stay raw."""
    text = str(value if value is not None else "").strip().replace("\\u00a0", " ").replace("\\u202f", " ").replace(",", ".")
    if " " in text:
        if not re.fullmatch(r"[+-]?\\d{1,3}(?: \\d{3})+(?:\\.\\d+)?", text):
            return None
        text = text.replace(" ", "")
    if not re.fullmatch(r"[+-]?(?:\\d+(?:\\.\\d*)?|\\.\\d+)", text):
        return None
    number = float(text)
    return number if math.isfinite(number) else None''')
            output = output.replace('if item["area_m2"] is not None and (item["room_number"] or item["room_name"]):',
                                    'if item["room_number"] or item["room_name"]:')
            changes = ["Keep blank rows in _prepare_table so proposed row numbers match raw rows",
                       "_num accepts only finite whole-cell scalars and valid space-separated thousands; ranges stay unresolved",
                       "Keep named/numbered room candidates when area is unresolved"]
        (package/(target+".py")).write_text(output, encoding="utf-8")
        records.append({"source": "proxy/services/"+mod+".py", "source_sha256_lf_utf8": hashlib.sha256(sources[mod].encode()).hexdigest(),
                        "target": target+".py", "symbols": sorted(selected[mod]), "changes": changes})
    (package/"LICENSE.txt").write_bytes((args.source/"LICENSE").read_bytes())
    (package/"provenance.json").write_text(json.dumps({"repository": "https://github.com/proovcme/les-list",
        "commit": COMMIT, "license": "MIT", "files": records}, ensure_ascii=False, indent=2)+"\n", encoding="utf-8")
    print("Vendored pure functions:", {MODULES[m]: len(s) for m,s in selected.items()})


if __name__ == "__main__":
    main()
